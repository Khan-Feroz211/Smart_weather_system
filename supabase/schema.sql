-- =============================================================================
-- Smart Weather System -- Supabase (PostgreSQL) schema
-- =============================================================================
-- Run once in the Supabase SQL Editor (or `psql "$SUPABASE_DB_URL" -f schema.sql`).
-- The script is idempotent: it can be re-run safely.
--
-- Contents
--   1. helper functions
--   2. users / admin_users (linked to Supabase Auth: auth.users)
--   3. weather + alerts + activity
--   4. agriculture
--   5. sensors
--   6. AI / prediction / experiments
--   7. admin audit log
--   8. indexes
--   9. Row Level Security + grants
--
-- Design notes
--   * The Flask backend connects with the database owner role (SUPABASE_DB_URL),
--     which bypasses RLS; it enforces authorisation itself. RLS protects the
--     public Supabase REST API (anon / authenticated keys) so the browser can
--     never read or write anything it should not.
--   * Legacy integer ids (farm_id, field_id, alert_id ...) are kept so existing
--     URLs / templates keep working. Users get a UUID primary key plus a stable
--     integer `user_number` (used by the legacy /user/<int> URLs).
--   * Event/audit times are timestamptz. Free-form planning dates typed into
--     forms (planted_date, expected_harvest_date, recommended_date) stay text
--     because the app accepts empty / non-ISO values there.
-- =============================================================================

