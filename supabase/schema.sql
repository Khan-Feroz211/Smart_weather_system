-- -----------------------------------------------------------------------------
-- 9. Row Level Security
--    * RLS is ENABLED on every table (never disabled to "make things work").
--    * anon has no access at all.
--    * authenticated users: own profile / own alerts / own activity, read-only
--      access to the shared weather + agriculture data, no writes.
--    * admins (public.is_admin()) can read everything.
--    * The Flask backend uses the database owner connection and enforces its
--      own authorisation; the service-role key is never sent to the browser.
-- -----------------------------------------------------------------------------
REVOKE ALL ON ALL TABLES    IN SCHEMA public FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.ensure_profile(uuid, text, jsonb, boolean) FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.handle_auth_user_change() FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION public.current_profile_id() FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.is_admin() FROM PUBLIC, anon;
GRANT  EXECUTE ON FUNCTION public.current_profile_id() TO authenticated;
GRANT  EXECUTE ON FUNCTION public.is_admin() TO authenticated;

DO $$
DECLARE t text;
BEGIN
    -- every table: RLS on
    FOREACH t IN ARRAY ARRAY[
        'users','admin_users','weather_data','user_activities','weather_alerts',
        'multi_hazard_alerts','hazard_probabilities','farms','fields','crop_census',
        'field_weather','crop_health','pest_risks','irrigation_recommendations',
        'yield_forecasts','agri_alerts','agri_feedback','raw_sensor_readings',
        'validated_sensor_readings','sensor_health','sensor_pipeline_logs',
        'sensor_quality_metrics','prediction_quality_metrics','experiments',
        'model_versions','dataset_versions','admin_audit_log']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_admin_read', t);
        EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (public.is_admin())',
                       t || '_admin_read', t);
        EXECUTE format('GRANT SELECT ON public.%I TO authenticated', t);
    END LOOP;

    -- shared, non-personal data: readable by any signed-in user
    FOREACH t IN ARRAY ARRAY[
        'weather_data','multi_hazard_alerts','hazard_probabilities','farms','fields',
        'crop_census','field_weather','crop_health','pest_risks',
        'irrigation_recommendations','yield_forecasts','agri_alerts']
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_read_authenticated', t);
        EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (true)',
                       t || '_read_authenticated', t);
    END LOOP;

    -- personal data: owner only
    FOREACH t IN ARRAY ARRAY['user_activities','weather_alerts']
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I', t || '_read_own', t);
        EXECUTE format('CREATE POLICY %I ON public.%I FOR SELECT TO authenticated USING (user_id = public.current_profile_id())',
                       t || '_read_own', t);
    END LOOP;
END $$;

-- users: a signed-in user sees and edits ONLY their own profile, and only these columns
-- (role / is_active / login counters can never be changed through the public API).
DROP POLICY IF EXISTS users_read_own ON public.users;
CREATE POLICY users_read_own ON public.users FOR SELECT TO authenticated
    USING (auth_user_id = auth.uid());

DROP POLICY IF EXISTS users_update_own ON public.users;
CREATE POLICY users_update_own ON public.users FOR UPDATE TO authenticated
    USING (auth_user_id = auth.uid()) WITH CHECK (auth_user_id = auth.uid());
GRANT UPDATE (username, location, preferences, phone_number) ON public.users TO authenticated;

