CREATE TABLE IF NOT EXISTS public.users (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    user_number     bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    auth_user_id    uuid UNIQUE REFERENCES auth.users (id) ON DELETE CASCADE,
    username        text NOT NULL,
    email           text NOT NULL,
    location        text NOT NULL DEFAULT '',
    phone_number    text,                                   -- E.164 phone for SMS / WhatsApp notifications
    totp_secret     text,                                   -- TOTP shared secret (NULL = 2FA not set up)
    two_factor_pending boolean NOT NULL DEFAULT FALSE,      -- set TRUE when user opts into 2FA during signup
    preferences     jsonb,
    role            text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    is_active       boolean NOT NULL DEFAULT true,
    is_online       boolean NOT NULL DEFAULT false,   -- informational only; activity is derived from last_seen_at
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    last_seen_at    timestamptz,
    last_login_at   timestamptz,
    login_count     integer NOT NULL DEFAULT 0
);
COMMENT ON COLUMN public.users.auth_user_id IS
    'Supabase Auth account. NULL for legacy profiles created before login existed. For new accounts id = auth_user_id.';

