-- Profile <-> Supabase Auth linking ------------------------------------------------
-- Creates (or links) the public.users profile for an Auth account.
-- A pre-existing legacy profile with the same email is linked ONLY when the
-- email is confirmed, so nobody can claim someone else's profile by signing up
-- with their address.
CREATE OR REPLACE FUNCTION public.ensure_profile(p_auth_id uuid, p_email text, p_meta jsonb, p_confirmed boolean)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_id uuid;
    v_base text;
    v_candidate text;
    v_n integer := 0;
BEGIN
    SELECT id INTO v_id FROM public.users WHERE auth_user_id = p_auth_id;
    IF FOUND THEN RETURN v_id; END IF;

    SELECT id INTO v_id FROM public.users
     WHERE lower(email) = lower(p_email) AND auth_user_id IS NULL;
    IF FOUND THEN
        IF p_confirmed THEN
            UPDATE public.users SET auth_user_id = p_auth_id WHERE id = v_id;
            RETURN v_id;
        END IF;
        RETURN NULL;   -- will be linked once the email is confirmed
    END IF;

    v_base := coalesce(nullif(trim(p_meta ->> 'username'), ''), split_part(p_email, '@', 1));
    v_base := regexp_replace(v_base, '[^A-Za-z0-9_.-]', '', 'g');
    IF v_base = '' THEN v_base := 'user'; END IF;
    v_candidate := v_base;
    WHILE EXISTS (SELECT 1 FROM public.users WHERE lower(username) = lower(v_candidate)) LOOP
        v_n := v_n + 1;
        v_candidate := v_base || v_n::text;
    END LOOP;

    INSERT INTO public.users (id, auth_user_id, username, email, location)
    VALUES (p_auth_id, p_auth_id, v_candidate, lower(p_email), coalesce(p_meta ->> 'location', ''))
    ON CONFLICT DO NOTHING;
    RETURN p_auth_id;
END $$;

CREATE OR REPLACE FUNCTION public.handle_auth_user_change()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    PERFORM public.ensure_profile(NEW.id, NEW.email, coalesce(NEW.raw_user_meta_data, '{}'::jsonb),
                                  NEW.email_confirmed_at IS NOT NULL);
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_auth_user_change();

DROP TRIGGER IF EXISTS on_auth_user_confirmed ON auth.users;
CREATE TRIGGER on_auth_user_confirmed AFTER UPDATE OF email_confirmed_at ON auth.users
    FOR EACH ROW WHEN (OLD.email_confirmed_at IS NULL AND NEW.email_confirmed_at IS NOT NULL)
    EXECUTE FUNCTION public.handle_auth_user_change();

-- RLS helper functions (SECURITY DEFINER so they can read users without recursion)
CREATE OR REPLACE FUNCTION public.current_profile_id()
RETURNS uuid LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT id FROM public.users WHERE auth_user_id = auth.uid()
$$;

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT EXISTS (
        SELECT 1
          FROM public.users u
          JOIN public.admin_users a ON a.user_id = u.id
         WHERE u.auth_user_id = auth.uid()
           AND u.role = 'admin' AND u.is_active AND a.is_active
    )
$$;

